"""AST-grounded Mermaid.js architecture diagram synthesizer addressing Gap 3."""

import re
from typing import Dict, List, Set, Tuple
from src.graph.dependency_graph import DependencyGraphBuilder
from src.models import RepositoryAST


class MermaidDiagramGenerator:
    """Generates and validates AST-grounded Mermaid.js flowcharts."""

    def __init__(self, repo_ast: RepositoryAST, graph_builder: DependencyGraphBuilder):
        self.repo_ast = repo_ast
        self.graph_builder = graph_builder

    def generate_diagram(self) -> str:
        """Synthesizes a clean, verified Mermaid.js flowchart."""
        lines = [
            "flowchart TD",
            "    %% Generated by RepoLens AST-Grounded Architecture Synthesizer",
            "    classDef module fill:#e1f5fe,stroke:#0288d1,stroke-width:1.5px,color:#01579b;",
            "    classDef entrypoint fill:#fff3e0,stroke:#f57c00,stroke-width:2px,color:#e65100;"
        ]

        # 1. Group files into subgraphs by directory
        dir_groups: Dict[str, List[str]] = {}
        for file_path in self.repo_ast.files.keys():
            parts = file_path.split("/")
            group_name = parts[0] if len(parts) > 1 else "root"
            dir_groups.setdefault(group_name, []).append(file_path)

        for group, files in sorted(dir_groups.items()):
            subgraph_id = f"subgraph_{self._sanitize_id(group)}"
            lines.append(f"    subgraph {subgraph_id} [\"{group.upper()} Module\"]")
            for f in sorted(files):
                node_id = self._sanitize_id(f)
                file_sym = self.repo_ast.files[f]
                # Label with classes or functions count
                meta = f"{len(file_sym.classes)}C / {len(file_sym.functions)}F"
                label = f"{Path(f).name}\\n[{meta}]" if 'Path' in globals() else f"{f.split('/')[-1]}\\n({meta})"
                cls_class = "entrypoint" if ("main" in f or "app" in f or "index" in f) else "module"
                lines.append(f"        {node_id}[\"{label}\"]:::{cls_class}")
            lines.append("    end")

        # 2. Add verified edges
        edges = self.graph_builder.get_edge_list()
        for src, dst in sorted(edges):
            src_id = self._sanitize_id(src)
            dst_id = self._sanitize_id(dst)
            edge_data = self.graph_builder.graph.get_edge_data(src, dst) or {}
            rel = edge_data.get("relation", "depends_on")
            lines.append(f"    {src_id} -->|{rel}| {dst_id}")

        return "\n".join(lines)

    @staticmethod
    def _sanitize_id(name: str) -> str:
        """Sanitizes names into valid Mermaid node identifiers."""
        clean = re.sub(r'[^a-zA-Z0-9_]', '_', name)
        if clean and clean[0].isdigit():
            clean = "n_" + clean
        return clean or "node"

    @classmethod
    def parse_mermaid_edges(cls, mermaid_code: str) -> List[Tuple[str, str]]:
        """Extracts (source, target) edges from Mermaid text for validation and GED computation."""
        edges = []
        edge_pattern = re.compile(r'([a-zA-Z0-9_]+)\s*-->(?:\|[^|]*\|)?\s*([a-zA-Z0-9_]+)')
        for line in mermaid_code.splitlines():
            line = line.strip()
            if line.startswith("%%") or line.startswith("flowchart") or line.startswith("subgraph") or line.startswith("end"):
                continue
            for match in edge_pattern.finditer(line):
                edges.append((match.group(1), match.group(2)))
        return edges

    @classmethod
    def parse_mermaid_nodes(cls, mermaid_code: str) -> Set[str]:
        """Extracts all declared node IDs from Mermaid text."""
        nodes = set()
        node_pattern = re.compile(r'([a-zA-Z0-9_]+)\[')
        for line in mermaid_code.splitlines():
            line = line.strip()
            if line.startswith("subgraph") or line.startswith("%%") or line.startswith("classDef"):
                continue
            for match in node_pattern.finditer(line):
                nodes.add(match.group(1))
        return nodes
