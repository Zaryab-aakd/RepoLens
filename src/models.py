"""Structured data schemas and contracts for RepoLens using Pydantic."""

from __future__ import annotations
from typing import List, Dict, Optional, Any
from pydantic import BaseModel, Field


class FunctionSymbol(BaseModel):
    """Metadata for a function or method extracted via AST."""
    name: str
    file_path: str
    line_number: int = 0
    arguments: List[str] = Field(default_factory=list)
    return_type: Optional[str] = None
    docstring: Optional[str] = None
    calls: List[str] = Field(default_factory=list)
    is_method: bool = False
    class_name: Optional[str] = None
    is_route: bool = False
    route_path: Optional[str] = None
    route_method: Optional[str] = None

    @property
    def qualified_name(self) -> str:
        if self.class_name:
            return f"{self.class_name}.{self.name}"
        return self.name

    @property
    def signature_str(self) -> str:
        prefix = f"{self.class_name}." if self.class_name else ""
        args = ", ".join(self.arguments)
        ret = f" -> {self.return_type}" if self.return_type else ""
        return f"{prefix}{self.name}({args}){ret}"


class ClassSymbol(BaseModel):
    """Metadata for a class definition extracted via AST."""
    name: str
    file_path: str
    line_number: int = 0
    docstring: Optional[str] = None
    methods: List[str] = Field(default_factory=list)
    base_classes: List[str] = Field(default_factory=list)


class ImportSymbol(BaseModel):
    """Metadata for imported modules and objects."""
    module: str
    imported_names: List[str] = Field(default_factory=list)
    is_relative: bool = False
    file_path: str = ""


class FileSymbols(BaseModel):
    """Collection of symbols extracted from a single source file."""
    file_path: str
    language: str  # "python" or "javascript" / "typescript"
    classes: Dict[str, ClassSymbol] = Field(default_factory=dict)
    functions: Dict[str, FunctionSymbol] = Field(default_factory=dict)
    imports: List[ImportSymbol] = Field(default_factory=list)
    loc: int = 0


class RepositoryAST(BaseModel):
    """Full repository-level AST symbol table and static call/dependency graph."""
    repo_name: str
    repo_path: str
    files: Dict[str, FileSymbols] = Field(default_factory=dict)
    total_loc: int = 0

    def get_all_function_names(self) -> List[str]:
        names = []
        for f in self.files.values():
            names.extend(f.functions.keys())
        return names

    def get_all_classes(self) -> List[str]:
        classes = []
        for f in self.files.values():
            classes.extend(f.classes.keys())
        return classes

    def get_symbol_map(self) -> Dict[str, FunctionSymbol]:
        mapping = {}
        for f in self.files.values():
            for name, sym in f.functions.items():
                mapping[sym.name] = sym
                mapping[sym.qualified_name] = sym
        return mapping


class VerificationIssue(BaseModel):
    """Details of a single hallucination or discrepancy detected by AST Verifier."""
    claim: str
    issue_type: str  # "ghost_function", "signature_mismatch", "invalid_route", "invalid_node", "broken_dependency"
    target_file: Optional[str] = None
    expected: Optional[str] = None
    actual: Optional[str] = None
    description: str
    suggested_correction: str


class VerificationReport(BaseModel):
    """Audit report generated by the deterministic AST Verifier Agent."""
    is_valid: bool
    total_claims: int
    verified_claims: int
    total_hallucinations: int
    hallucination_rate: float
    precision: float
    recall: float
    issues: List[VerificationIssue] = Field(default_factory=list)
    audit_notes: str = ""


class TrajectoryStep(BaseModel):
    """A single observable reasoning step, tool call, or verification action."""
    step_id: int
    agent_role: str  # "ScannerAgent", "SynthesizerAgent", "VerifierAgent", "Orchestrator"
    action: str
    thought: str
    input_payload: Dict[str, Any] = Field(default_factory=dict)
    output_payload: Dict[str, Any] = Field(default_factory=dict)
    timestamp: float
    error: Optional[str] = None


class AgentTrajectory(BaseModel):
    """Full sequence of observable execution traces for an agentic run."""
    repo_name: str
    steps: List[TrajectoryStep] = Field(default_factory=list)
    total_steps: int = 0
    correction_iterations: int = 0
    duration_seconds: float = 0.0


class RepoLensOutput(BaseModel):
    """Complete output produced by the RepoLens pipeline."""
    repo_name: str
    readme_markdown: str
    mermaid_diagram: str
    verification_report: VerificationReport
    trajectory: AgentTrajectory
    iterations_used: int
    ablation_flags: Dict[str, bool] = Field(default_factory=dict)
